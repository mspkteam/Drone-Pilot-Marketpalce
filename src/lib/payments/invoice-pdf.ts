import PDFDocument from "pdfkit";
import type { PaymentListItemDto } from "@/types/payment";

const GOLD = "#b8962e";
const INK = "#141414";
const MUTED = "#5c5c5c";

function money(amount: number, currency: string) {
  return `${currency} ${amount.toLocaleString(undefined, {
    minimumFractionDigits: 2,
    maximumFractionDigits: 2,
  })}`;
}

/** Simple RAS invoice/receipt PDF for a client payment row. */
export function renderPaymentInvoicePdf(
  payment: PaymentListItemDto,
  invoiceLabel: string,
): Promise<Buffer> {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({
      size: "LETTER",
      margins: { top: 56, bottom: 56, left: 56, right: 56 },
      info: {
        Title: invoiceLabel,
        Author: "Remote Air Service",
        Subject: "Job payment receipt",
      },
    });
    const chunks: Buffer[] = [];
    doc.on("data", (chunk: Buffer) => chunks.push(chunk));
    doc.on("end", () => resolve(Buffer.concat(chunks)));
    doc.on("error", reject);

    const total = payment.amountGross + (payment.serviceFeeAmount ?? 0);
    const date = new Date(payment.createdAt).toLocaleDateString("en-US", {
      year: "numeric",
      month: "long",
      day: "numeric",
    });

    doc.font("Helvetica-Bold").fontSize(18).fillColor(INK).text("Remote Air Service");
    doc.font("Helvetica").fontSize(10).fillColor(GOLD).text("Payment receipt", { continued: false });
    doc.moveDown(1.5);

    doc.font("Helvetica-Bold").fontSize(12).fillColor(INK).text(invoiceLabel);
    doc.font("Helvetica").fontSize(10).fillColor(MUTED).text(`Date: ${date}`);
    doc.text(`Status: ${payment.status}`);
    doc.text(`Provider: ${payment.provider}`);
    doc.moveDown();

    doc.font("Helvetica-Bold").fontSize(11).fillColor(INK).text("Project");
    doc.font("Helvetica").fontSize(10).fillColor(MUTED).text(payment.booking.job.title);
    doc.text(`Pilot: ${payment.counterpartyLabel}`);
    doc.moveDown();

    doc.font("Helvetica-Bold").fontSize(11).fillColor(INK).text("Amounts");
    doc.font("Helvetica").fontSize(10).fillColor(MUTED);
    doc.text(`Job amount: ${money(payment.amountGross, payment.currency)}`);
    doc.text(
      `Service fee (6%): ${money(payment.serviceFeeAmount ?? 0, payment.currency)}`,
    );
    doc.moveDown(0.5);
    doc.font("Helvetica-Bold").fontSize(12).fillColor(INK).text(
      `Total charged: ${money(total, payment.currency)}`,
    );
    if (payment.commission) {
      doc.moveDown(0.5);
      doc.font("Helvetica").fontSize(9).fillColor(MUTED).text(
        `Platform commission (pilot side): ${money(payment.commission.amount, payment.currency)} at ${(payment.commission.rate * 100).toFixed(0)}%.`,
      );
    }

    doc.moveDown(2);
    doc.font("Helvetica").fontSize(8).fillColor(MUTED).text(
      "This receipt is generated by Remote Air Service for your records. Escrowed funds are held until delivery is approved or auto-released per platform terms.",
      { width: 480 },
    );

    doc.end();
  });
}
